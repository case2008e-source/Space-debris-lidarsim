# %matplotlib widget

import random
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

# 3. ENVIRONMENT SETUP
debris_x = 0.0
debris_y = 10.0
debris_z = 5.0

velocity_x = 1.5
velocity_y = 0.5
velocity_z = 1.0
dt = 1.0

x_history = []
y_history = []
z_history = []

print("--- STARTING ACTIVE DEBRIS DETECTION SIMULATION ---")

# 4.  Debris simulation 
for second in range(1, 11):
    debris_x = debris_x + (velocity_x * dt)
    debris_y = debris_y + (velocity_y * dt)
    debris_z = debris_z + (velocity_z * dt)

    x_history.append(debris_x)
    y_history.append(debris_y)
    z_history.append(debris_z)

    true_distance = (debris_x**2 + debris_y**2 + debris_z**2) ** 0.5
    sensor_noise = random.uniform(-0.3, 0.3)
    measured_distance = true_distance + sensor_noise

    CRITICAL_ZONE = 14.0
    WARNING_ZONE = 18.0

    if measured_distance <= CRITICAL_ZONE:
        status = "🚨 CRITICAL: Immediate Collision Hazard!"
    elif measured_distance <= WARNING_ZONE:
        status = "⚠️ WARNING: Object entering proximity vector."
    else:
        status = "✅ SAFE: Monitoring object path."

    print(f"Time: {second}s | True Pos: ({debris_x:.2f}, {debris_y:.2f}, {debris_z:.2f})m")
    print(f"       | LiDAR Measured Distance: {measured_distance:.2f}m (Error: {sensor_noise:.2f}m)")
    print(f"       | Threat Assessment: {status}")
    print("-" * 60)

print("\nSimulation complete. Generating Interactive 3D Trajectory Visualization...")

# 5. 3D PLOT
fig = plt.figure(figsize=(9, 6))
ax = fig.add_subplot(111, projection='3d')

ax.scatter(0, 0, 0, color='blue', s=200, label='LiDAR Sensor (Origin)', marker='^')
ax.plot(x_history, y_history, z_history, color='red', linestyle='--', linewidth=2, label='Debris Trajectory')
ax.scatter(x_history, y_history, z_history, color='black', s=50)

ax.set_title("3D Space Debris Trajectory Mapping via LiDAR Tracking", fontsize=12, fontweight='bold')
ax.set_xlabel("X-Axis: Lateral Displacement (m)")
ax.set_ylabel("Y-Axis: Range Displacement (m)")
ax.set_zlabel("Z-Axis: Altitude/Height (m)")
ax.legend(loc='upper left')

ax.grid(True)
plt.show()
